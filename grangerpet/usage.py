"""Actual provider usage, independent of local cost guards and context estimates.

The database contains counts and opaque local identifiers, never prompts,
responses, credentials or HTTP headers. No guessed balance endpoint is called.
"""
from __future__ import annotations

import re
import sqlite3
from contextlib import contextmanager
from pathlib import Path
import uuid

from .agent_evidence import utc_now
from .config import data_directory


TOKEN_FIELDS = ("prompt_tokens", "completion_tokens", "total_tokens")
UNKNOWN_BALANCE = {"status": "unknown", "message": "Провайдер не предоставляет данные об остатке"}


def actual_usage(metadata):
    value = metadata.get("usage", {}) if isinstance(metadata, dict) else {}
    if not isinstance(value, dict):
        return {}
    return {key: value[key] for key in TOKEN_FIELDS
            if type(value.get(key)) is int and 0 <= value[key] <= 2**63 - 1}


def usage_totals(requests):
    """Unknown usage stays unknown; missing counts are never estimated here."""
    requests = list(requests)
    known = [row.get("usage", {}) for row in requests]
    result = {"requests": len(requests),
              "successful_requests": sum(row.get("status") == "success" for row in requests),
              "failed_requests": sum(row.get("status") in ('error', 'timeout', 'cancelled') for row in requests),
              "pending_requests": sum(row.get("status") == 'in_flight' for row in requests),
              "usage_reported_requests": sum(bool(value) for value in known),
              "usage_missing_requests": sum(not value for value in known)}
    for key in TOKEN_FIELDS:
        values = [value[key] for value in known if type(value.get(key)) is int]
        result[key] = sum(values) if values else None
    result["partial_usage"] = any(any(key not in value for key in TOKEN_FIELDS) for value in known)
    return result


class UsageLedger:
    def __init__(self, path=None):
        self.path = Path(path) if path is not None else data_directory() / "usage.sqlite3"

    @contextmanager
    def _connect(self):
        self.path.parent.mkdir(parents=True, exist_ok=True)
        connection = sqlite3.connect(self.path, timeout=5)
        connection.execute("PRAGMA busy_timeout=5000")
        connection.execute("""CREATE TABLE IF NOT EXISTS requests (
            request_id TEXT PRIMARY KEY, obtained_at TEXT NOT NULL,
            provider TEXT NOT NULL, model TEXT NOT NULL, conversation_id TEXT,
            investigation_id TEXT, status TEXT NOT NULL, error_code TEXT,
            prompt_tokens INTEGER, completion_tokens INTEGER, total_tokens INTEGER)""")
        try:
            with connection:
                yield connection
        finally:
            connection.close()

    @staticmethod
    def _identifier(value):
        # IDs are generated by the app, not a place to store user message text.
        if value is None:
            return None
        value = str(value)
        if not re.fullmatch(r"[A-Za-z0-9_-]{1,128}", value):
            raise ValueError("Invalid usage identifier")
        return value

    def _record(self, metadata, *, provider="deepseek", model="", conversation_id=None,
                investigation_id=None, request_id=None, status="success", error_code=None):
        if status not in ("success", "error", "timeout", "cancelled"):
            raise ValueError("Invalid request status")
        usage = actual_usage(metadata)
        row = {"request_id": self._identifier(request_id or uuid.uuid4().hex), "obtained_at": utc_now(),
               "provider": str(provider)[:80], "model": str(model)[:160],
               "conversation_id": self._identifier(conversation_id),
               "investigation_id": self._identifier(investigation_id),
               "status": status, "error_code": str(error_code)[:80] if error_code else None, "usage": usage}
        # A stable id makes timeout followed by a late provider reply idempotent.
        with self._connect() as connection:
            connection.execute("""INSERT INTO requests VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                ON CONFLICT(request_id) DO UPDATE SET obtained_at=excluded.obtained_at,
                status=CASE WHEN requests.status='success' THEN requests.status ELSE excluded.status END,
                error_code=CASE WHEN requests.status='success' THEN requests.error_code ELSE excluded.error_code END,
                prompt_tokens=COALESCE(excluded.prompt_tokens,requests.prompt_tokens),
                completion_tokens=COALESCE(excluded.completion_tokens,requests.completion_tokens),
                total_tokens=COALESCE(excluded.total_tokens,requests.total_tokens)""",
                (row["request_id"], row["obtained_at"], row["provider"], row["model"],
                 row["conversation_id"], row["investigation_id"], row["status"], row["error_code"],
                 *(usage.get(key) for key in TOKEN_FIELDS)))
        return row

    def record_response(self, metadata, *, provider="deepseek", model="", conversation_id=None,
                        investigation_id=None, request_id=None):
        return self._record(metadata, provider=provider, model=model, conversation_id=conversation_id,
                            investigation_id=investigation_id, request_id=request_id)

    def record_error(self, error=None, *, provider="deepseek", model="", conversation_id=None,
                     investigation_id=None, request_id=None, status="error", error_code=None):
        code = error_code or getattr(error, "code", None)
        return self._record({}, provider=provider, model=model, conversation_id=conversation_id,
                            investigation_id=investigation_id, request_id=request_id,
                            status=status, error_code=code)

    def snapshot(self, conversation_id=None, investigation_id=None):
        filters, values = [], []
        for key, value in (("conversation_id", conversation_id), ("investigation_id", investigation_id)):
            if value is not None:
                filters.append(key + " = ?")
                values.append(self._identifier(value))
        if not self.path.exists():
            rows = []
        else:
            with self._connect() as connection:
                connection.row_factory = sqlite3.Row
                records = connection.execute("SELECT * FROM requests" +
                    (" WHERE " + " AND ".join(filters) if filters else "") + " ORDER BY obtained_at", values).fetchall()
            rows = []
            for record in records:
                row = dict(record)
                row["usage"] = {key: row.pop(key) for key in TOKEN_FIELDS if row.get(key) is not None}
                for key in TOKEN_FIELDS:
                    row.pop(key, None)
                rows.append(row)
        return {"totals": usage_totals(rows), "last_request": rows[-1] if rows else None,
                "provider_balance": dict(UNKNOWN_BALANCE), "context_window": None,
                "context_window_status": "unknown"}
