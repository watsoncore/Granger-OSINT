def select(data,path,*,required=True):
    if path.startswith('='):return path[1:]
    if path=='@':return data
    try:
        for part in path.split('/'):
            data=data[int(part)] if isinstance(data,list) and part.isdigit() else data[part]
        return data
    except (KeyError,IndexError,TypeError):
        if required:raise ValueError('Provider schema changed: '+path) from None
        return None


def request(definition,query,limit):
    replacements={'query':query,'limit':str(limit)}
    if definition.kind=='coordinates':
        from .geoint.mapping import coordinates
        latitude,longitude=coordinates(query);replacements.update(lat=str(latitude),lon=str(longitude))
    def replace(value,encoded=False):
        for key,item in replacements.items():value=value.replace('{'+key+'}',quote(item,safe='') if encoded else item)
        return value
    url=replace(definition.endpoint,True)
    if definition.provider in ('huggingface','scorecard'):
        # Two separately validated path segments; these APIs reject encoded '/'.
        url=definition.endpoint.replace('{query}','/'.join(quote(part,safe='') for part in query.split('/')))
    params={key:replace(value) for key,value in definition.params}
    return url,params


def parse(definition,data,limit):
    from .source_adapters import text
    from .engine.models import canonical_url
    records=select(data,definition.records)
    if isinstance(records,dict):records=[records]
    if not isinstance(records,list) or any(not isinstance(row,dict) for row in records):raise ValueError('Expected records')
    result=[]
    for row in records[:limit]:
        identifier=select(row,definition.identifier);title=text(select(row,definition.title),400)
        if isinstance(identifier,(dict,list,bool)) or identifier is None or not title:raise ValueError('Invalid canonical entity')
        fields={key:select(row,path,required=False) for key,path in definition.fields}
        fields={key:text(value) if isinstance(value,(str,list)) else value for key,value in fields.items() if type(value) in (str,int,float,bool,list)}
        if definition.url_field:url=select(row,definition.url_field)
        else:
            url=definition.url.replace('{id}',quote(str(identifier),safe=''))
            for key,value in fields.items():
                url=url.replace('{'+key+'}',quote(str(value),safe=''))
        url=canonical_url(url) if isinstance(url,str) else ''
        if not url or '{' in url:raise ValueError('Invalid evidence URL')
        result.append({'canonical_identifier':definition.provider+':'+str(identifier),'entity_type':definition.entity,
            'title':title,'url':url,'fields':fields,'description':text(fields.get('description') or fields.get('public_bio')),
            'candidate':definition.candidate})
    return result
